"""
Quiz Module for EduGenie
Generates 3 multiple-choice questions (MCQs) with 4 options each,
the correct answer, and an educational explanation.
Parses structured JSON and strips markdown fences with clean_json_block.
"""

import json
import logging
from gemini_client import ask_gemini, clean_json_block

logger = logging.getLogger(__name__)


def generate_quiz(text: str) -> list[dict]:
    """
    Generates a 3-question MCQ quiz based on the provided topic or text passage.
    Returns a list of dictionaries with question, options, answer, and explanation.
    """
    cleaned_input = text.strip()
    if not cleaned_input:
        return [
            {
                "question": "No topic was provided for the quiz.",
                "options": ["Enter a topic", "Try again", "Read documentation", "Refresh"],
                "answer": "Enter a topic",
                "explanation": "Please enter a valid topic or passage to generate a quiz."
            }
        ]

    prompt = f"""Create exactly 3 multiple-choice questions about the following topic or passage.

Topic/Passage:
{cleaned_input}

Return ONLY valid JSON with no conversational text or markdown explanation.

Format:
{{
  "questions": [
    {{
      "question": "Clear and specific question here",
      "options": [
        "Option A",
        "Option B",
        "Option C",
        "Option D"
      ],
      "answer": "Option A",
      "explanation": "Short explanation of why this answer is correct"
    }}
  ]
}}

Rules:
- Exactly 3 questions.
- Exactly 4 distinct options per question.
- One correct answer per question.
- The 'answer' string MUST EXACTLY match one of the strings in the 'options' list.
- Questions must be educational, challenging yet fair.
"""

    raw_response = ask_gemini(prompt)

    # Check if Gemini returned an error / API key warning string
    if "Gemini API key is missing" in raw_response or "Gemini connection error" in raw_response:
        return [
            {
                "question": "Gemini API Error",
                "options": [
                    "Check GEMINI_API_KEY in .env",
                    "Verify internet connection",
                    "Restart the server",
                    "All of the above"
                ],
                "answer": "All of the above",
                "explanation": raw_response
            }
        ]

    try:
        cleaned = clean_json_block(raw_response)
        data = json.loads(cleaned)

        questions = data.get("questions", [])

        # Validate quiz format
        if not isinstance(questions, list) or len(questions) == 0:
            raise ValueError("Parsed JSON did not contain a valid questions list.")

        # Validate each question
        sanitized = []
        for q in questions[:3]:
            q_text = str(q.get("question", "Question"))
            opts = [str(opt) for opt in q.get("options", [])]
            ans = str(q.get("answer", ""))
            exp = str(q.get("explanation", ""))

            # Ensure 4 options
            while len(opts) < 4:
                opts.append(f"Option {len(opts) + 1}")
            opts = opts[:4]

            # Ensure answer matches one option
            if ans not in opts:
                ans = opts[0]

            sanitized.append({
                "question": q_text,
                "options": opts,
                "answer": ans,
                "explanation": exp or "Correct answer according to reference material."
            })

        return sanitized

    except Exception as error:
        logger.error("Failed to parse quiz JSON: %s. Raw was: %s", error, raw_response)
        return [
            {
                "question": "Could not automatically parse the quiz generated by AI.",
                "options": [
                    "Try again with a more specific topic",
                    "Check API key and rate limits",
                    "Shorten the input text",
                    "All of the above"
                ],
                "answer": "All of the above",
                "explanation": f"Parser error details: {error}"
            }
        ]
